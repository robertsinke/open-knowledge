const FILE_ICON_LUCIDE = {
  File: LucideFile,
  Film: LucideFilm,
  FolderOpen: LucideFolderOpen,
  ImageIcon: LucideImageIcon,
  Volume2: LucideVolume2,
} as const;

export type FileIconName = keyof typeof FILE_ICON_LUCIDE;

export function hostIconSet(name: string): 'hugeicons' | 'lucide' {
  if (isBbEditorHost() && Object.hasOwn(HUGE_BY_NAME, name)) return 'hugeicons';
  return 'lucide';
}

function hugeIconSvg(icon: IconSvgElement, name: string): string {
  const body = icon
    .map(([tag, attrs]) => {
      const rendered = Object.entries(attrs)
        .filter(([key]) => key !== 'key')
        .map(([key, value]) => `${key}="${value}"`)
        .join(' ');
      return `<${tag} ${rendered}/>`;
    })
    .join('');
  return (
    '<svg xmlns="http://www.w3.org/2000/svg" width="0.75rem" height="0.75rem"' +
    ' viewBox="0 0 24 24" fill="none" aria-hidden="true"' +
    ` data-icon-set="hugeicons" data-icon-name="${name}">${body}</svg>`
  );
}

export function fileIconSvg(name: FileIconName): string {
  const huge = isBbEditorHost() ? HUGE_BY_NAME[name] : undefined;
  if (huge) return hugeIconSvg(huge, name);
  return lucideIconToSvgString(FILE_ICON_LUCIDE[name]);
}

function bind(name: string, Lucide: LucideIcon, huge: IconSvgElement | null): LucideIcon {
  const Icon = ((props: LucideProps) => {
    const marker = {
      'data-icon-set': huge && isBbEditorHost() ? 'hugeicons' : 'lucide',
      'data-icon-name': name,
    };
    if (huge && isBbEditorHost()) {
      const { strokeWidth, ...rest } = props;
      return (
        <HugeiconsIcon
          icon={huge}
          {...rest}
          strokeWidth={typeof strokeWidth === 'number' ? Number(strokeWidth) : undefined}
          {...marker}
        />
      );
    }
    return <Lucide {...props} {...marker} />;
  }) as LucideIcon;
  return Icon;
}

